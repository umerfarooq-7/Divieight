/**
 * The Year-End packet as a human-readable PDF (same writer as the monthly statement: Helvetica, never smaller than 11 pt). The roster shows
 * whether a TIN is on file, never the TIN: TINs are only in the separate private files.
 */
import { Doc, emitPdf } from "@/lib/statement-pdf";
import { statementMoney } from "@/lib/statements";
import type { PacketPayload } from "@/lib/year-end-packet";

export function renderPacketPdf(p: PacketPayload, version: number, hash: string): Uint8Array<ArrayBuffer> {
  const doc = new Doc();
  const m = statementMoney;
  const name = new Map(p.members.map((x) => [x.member_key, x.legal_name]));
  doc.text(`Year-End CPA Export Packet ${p.period.year}`, { size: 18, bold: true });
  doc.text(p.property.llc_name ?? "LLC", { size: 13, bold: true });
  doc.text([p.property.address, p.property.city, p.property.state].filter(Boolean).join(", "));
  doc.text(`Version ${version} · ${p.trigger === "scheduled" ? "generated by the scheduled job" : "generated by the Manager"} · ${p.generated_at.slice(0, 10)}`);
  doc.text(`Hash ${hash}`);
  doc.text("Books only. This packet contains no K-1, no Form 1065, no depreciation and no Section 754 figure.");

  doc.heading("Contents");
  doc.text("Trial balance · Balance sheet · Income statement · Capital account roll-forward · Member roster · 1099 forms · CPA Cooperation Worksheet · General ledger. The same data is in CSV and XLSX (one file per section) and in JSON for tax software.");

  doc.heading(`Trial balance as of ${p.trial_balance.as_of}`);
  for (const r of p.trial_balance.rows as Array<Record<string, any>>) doc.row(`${r.code}  ${r.name}`, `Dr ${m(r.debit_cents)}   Cr ${m(r.credit_cents)}`);
  doc.row("Total", `Dr ${m(p.trial_balance.total_debit_cents)}   Cr ${m(p.trial_balance.total_credit_cents)}`, { bold: true });
  doc.text(p.trial_balance.balanced ? "The trial balance balances." : "THE TRIAL BALANCE DOES NOT BALANCE.", { bold: true });

  doc.heading(`Balance sheet as of ${p.balance_sheet.as_of}`);
  doc.text("Assets", { bold: true });
  for (const a of p.balance_sheet.assets as Array<Record<string, any>>) doc.row(`${a.code}  ${a.name}`, m(a.balance_cents), { indent: 12 });
  doc.row("Total assets", m(p.balance_sheet.total_assets_cents), { bold: true });
  doc.text("Capital", { bold: true });
  for (const c of p.balance_sheet.member_capital as Array<Record<string, any>>) doc.row(name.get(c.member_key) ?? `Member ${String(c.member_key).slice(0, 8)}`, m(c.balance_cents), { indent: 12 });
  doc.row("Earned and not yet allocated to the members", m(p.balance_sheet.unallocated_net_income_cents ?? 0), { indent: 12 });
  doc.row("Total liabilities and capital", m(p.balance_sheet.total_liabilities_and_equity_cents), { bold: true });

  doc.heading(`Income statement ${p.period.year}`);
  for (const [title, accounts] of [["Income", p.income_statement.income], ["Expense", p.income_statement.expense]] as Array<[string, Array<Record<string, any>>]>) {
    doc.text(title, { bold: true });
    if (accounts.length === 0) doc.text("None.", { x: 66 });
    for (const a of accounts) {
      doc.row(`${a.code}  ${a.name}`, m(a.total_cents), { indent: 12, bold: true });
      for (const i of a.items as Array<Record<string, any>>) doc.item(i.date, i.memo, m(i.amount_cents), 24);
    }
  }
  doc.row("Net income (expense)", m(p.income_statement.net_cents), { bold: true });
  const alloc = p.income_statement.allocated_to_members as Record<string, number> | undefined;
  if (alloc) doc.text(`Passed on to the members: income ${m(alloc.income_allocated_cents ?? 0)}, expense ${m(alloc.expense_allocated_cents ?? 0)}.`);

  doc.heading(`Capital account roll-forward ${p.period.year}`);
  for (const r of p.roll_forwards) {
    doc.text(name.get(r.member_key as string) ?? `Member ${String(r.member_key).slice(0, 8)}`, { bold: true });
    for (const [k, v] of [["Beginning", r.beginning_cents], ["Contributions", r.contributions_cents], ["Distributions", r.distributions_cents], ["Allocable income", r.income_cents], ["Allocable expense", r.expense_cents], ["Allocable depreciation", r.depreciation_cents], ["Shares bought and sold", r.transfers_cents ?? 0], ["Ending", r.ending_cents]] as Array<[string, number]>) doc.row(k, m(v), { indent: 12, bold: k === "Ending" });
  }

  doc.heading("Member roster");
  doc.text("Legal name, share count, mailing address. TINs are in the separate private file, not here.");
  for (const x of p.members) {
    doc.row(x.legal_name, `${x.share_count} share${x.share_count === 1 ? "" : "s"} · ${x.interest_percent}%`, { bold: true });
    doc.text(`${x.mailing_address ?? "No mailing address on file"} · TIN ${x.tin_status === "on_file" ? `on file (${(x.tin_kind ?? "").toUpperCase()})` : "not on file"}`, { x: 66 });
  }

  doc.heading("1099 forms issued to LLC vendors");
  if (p.forms_1099.length === 0) doc.text("The platform issued no 1099 forms to this LLC's vendors in this year.");
  for (const f of p.forms_1099) doc.row(`${f.vendor_name} · ${f.form_type}`, m(f.amount_cents));

  doc.heading("CPA Cooperation Worksheet");
  doc.text("Flags for the CPA. The platform computes no depreciation and no Section 754 step-up.");
  if (p.worksheet.items.length === 0) doc.text("Nothing is flagged.");
  for (const i of p.worksheet.items) {
    doc.text(`${i.title} (${i.status})`, { bold: true });
    if (i.manager_note) doc.text(`Manager's note: ${i.manager_note}`, { x: 66 });
  }

  doc.heading(`General ledger ${p.period.year}`);
  doc.text(`${p.totals.entries} entries. Debits ${m(p.totals.debit_cents)} · Credits ${m(p.totals.credit_cents)}.`);
  for (const e of p.entries as Array<Record<string, any>>) {
    doc.text(`${e.date}  ${e.memo || e.source}${e.reverses_entry_id ? " (reversal)" : ""}${e.bank?.merchant ? ` [${e.bank.merchant}${e.bank.raw_category ? `, ${e.bank.raw_category}` : ""}]` : ""}`, { bold: true });
    for (const l of e.lines as Array<Record<string, any>>) doc.row(`${l.account_code} ${l.account_name}`, l.debit_cents ? `Dr ${m(l.debit_cents)}` : `Cr ${m(l.credit_cents)}`, { indent: 12 });
  }
  return emitPdf(doc, `Year-End CPA Export Packet ${p.period.year}`);
}
